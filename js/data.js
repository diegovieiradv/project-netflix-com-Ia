export const allMovies = categories.flatMap(cat => cat.items.map(item => ({
    ...item,
    category: item.category || cat.title
})));

export function getAllMovies() {
    const seen = new Set();
    return categories.flatMap(function(c) { return c.items; }).filter(function(m) {
        if (seen.has(m.title)) return false;
        seen.add(m.title);
        return true;
    });
}

